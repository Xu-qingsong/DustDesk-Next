import assert from 'node:assert/strict'
import { access, mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { launchTauri, waitFor } from './tauri-harness.mjs'

const application = await launchTauri()
const { invoke, page, findPage } = application
const failures = []
page.on('pageerror', error => failures.push(String(error)))
try {
  const initial = await invoke('prototype_diagnostics')
  assert.equal(initial.preview, true)
  assert.equal(initial.version, JSON.parse(await readFile('package.json', 'utf8')).version)
  assert.equal(initial.windows.length, 1)
  assert.ok(initial.profileDirectory.startsWith(application.root))
  assert.ok(initial.monitors.length > 0)
  const monitor = initial.monitors[0]
  await page.getByRole('button', { name: '透明小组件', exact: true }).click()
  const widget = await findPage('widget')
  await widget.getByRole('textbox', { name: '验证中文输入' }).fill('中文输入验证，不触碰正式便签')
  assert.equal(await widget.getByRole('textbox', { name: '验证中文输入' }).inputValue(), '中文输入验证，不触碰正式便签')
  await assert.rejects(invoke('prototype_open_window', { kind: 'pin' }, widget), /无权/)
  await assert.rejects(invoke('prototype_capture_region', { rect: { x: monitor.x, y: monitor.y, width: 8, height: 8 } }, widget), /无截图权限/)
  await assert.rejects(invoke('prototype_control_window', { label: 'main', options: { visible: false } }, widget), /其他窗口/)
  await assert.rejects(invoke('prototype_open_window', { kind: '../escape' }), /未知/)
  await assert.rejects(invoke('prototype_control_window', { label: 'main', options: { mouseThrough: true } }), /不能/)
  await invoke('prototype_control_window', { label: 'probe-widget', options: { x: monitor.x + 80, y: monitor.y + 80, width: 420, height: 280, topmost: false, opacity: 128, mouseThrough: true } })
  let state = await invoke('prototype_diagnostics')
  let native = state.windows.find(window => window.label === 'probe-widget')
  assert.equal(native.width, 420)
  assert.equal(native.height, 280)
  assert.equal(native.x, monitor.x + 80)
  assert.equal(native.y, monitor.y + 80)
  assert.equal(native.alwaysOnTop, false)
  assert.equal(native.opacity, 128)
  assert.equal(native.mouseThrough, true)
  await assert.rejects(invoke('prototype_control_window', { label: 'probe-widget', options: { topmost: true, opacity: 0 } }), /透明度/)
  native = (await invoke('prototype_diagnostics')).windows.find(window => window.label === 'probe-widget')
  assert.equal(native.alwaysOnTop, false, 'Invalid option batches cannot partially change a window')
  await invoke('prototype_restore_windows')
  native = (await invoke('prototype_diagnostics')).windows.find(window => window.label === 'probe-widget')
  assert.equal(native.mouseThrough, false)
  assert.equal(native.opacity, 255)
  assert.equal(native.visible, true)
  const windowPng = await page.evaluate(async () => Array.from(new Uint8Array(await window.__TAURI_INTERNALS__.invoke('prototype_capture_window', { label: 'probe-widget' }))))
  const windowBytes = Buffer.from(windowPng)
  assert.deepEqual([...windowBytes.subarray(0, 8)], [137, 80, 78, 71, 13, 10, 26, 10])
  assert.equal(windowBytes.readUInt32BE(16), 420)
  assert.equal(windowBytes.readUInt32BE(20), 280)
  await assert.rejects(invoke('prototype_capture_window', { label: 'probe-widget' }, widget), /无权/)
  await assert.rejects(invoke('prototype_capture_window', { label: 'main' }), /仅允许/)
  await invoke('prototype_open_window', { kind: 'overlay', monitor: 0 })
  const overlay = await findPage('overlay')
  await overlay.locator('.probe-overlay').waitFor()
  native = (await invoke('prototype_diagnostics')).windows.find(window => window.label === 'probe-overlay')
  assert.equal(native.x, monitor.x)
  assert.equal(native.y, monitor.y)
  assert.equal(native.width, monitor.width)
  assert.equal(native.height, monitor.height)
  await overlay.keyboard.press('Escape')
  await waitFor(async () => !(await invoke('prototype_diagnostics')).windows.find(window => window.label === 'probe-overlay').visible)
  await invoke('prototype_open_window', { kind: 'overlay', monitor: 0 })
  await assert.rejects(invoke('prototype_capture_region', { rect: { x: monitor.x, y: monitor.y, width: 0, height: 20 } }), /尺寸/)
  assert.equal((await invoke('prototype_diagnostics')).windows.find(window => window.label === 'probe-overlay').visible, true, 'Invalid captures do not hide the selection window')
  await assert.rejects(invoke('prototype_capture_region', { rect: { x: -65536, y: -65536, width: 8, height: 8 } }), /屏幕范围/)
  assert.equal((await invoke('prototype_diagnostics')).windows.find(window => window.label === 'probe-overlay').visible, true, 'A failed native capture restores the selection window for retry')
  const png = await page.evaluate(async rect => Array.from(new Uint8Array(await window.__TAURI_INTERNALS__.invoke('prototype_capture_region', { rect }))), { x: monitor.x, y: monitor.y, width: 32, height: 24 })
  const bytes = Buffer.from(png)
  assert.deepEqual([...bytes.subarray(0, 8)], [137, 80, 78, 71, 13, 10, 26, 10])
  assert.equal(bytes.readUInt32BE(16), 32)
  assert.equal(bytes.readUInt32BE(20), 24)
  assert.equal((await invoke('prototype_diagnostics')).windows.find(window => window.label === 'probe-overlay').visible, false)
  await invoke('prototype_control_window', { label: 'main', options: { x: monitor.x + 20, y: monitor.y + 20, topmost: true } })
  await page.evaluate(() => { const marker = document.createElement('div'); marker.id = 'capture-pixel-marker'; Object.assign(marker.style, { position: 'fixed', inset: '0', background: 'rgb(217, 35, 77)', zIndex: '2147483647' }); document.body.append(marker) })
  await page.waitForTimeout(100)
  await invoke('prototype_open_window', { kind: 'overlay', monitor: 0 })
  await overlay.mouse.move(120, 140)
  await overlay.mouse.down()
  await overlay.mouse.move(300, 220, { steps: 6 })
  await overlay.mouse.up()
  await overlay.locator('.probe-selection').waitFor()
  await overlay.keyboard.press('Enter')
  await waitFor(async () => !(await invoke('prototype_diagnostics')).windows.find(window => window.label === 'probe-overlay').visible)
  await page.getByAltText('确认选区后捕获的桌面区域').waitFor()
  await waitFor(() => page.getByAltText('确认选区后捕获的桌面区域').evaluate((image, width) => image.naturalWidth === width, Math.round(180 * monitor.scaleFactor)))
  const capturedPixel = await page.getByAltText('确认选区后捕获的桌面区域').evaluate(image => { const canvas = document.createElement('canvas'); canvas.width = image.naturalWidth; canvas.height = image.naturalHeight; const context = canvas.getContext('2d'); context.drawImage(image, 0, 0); return [...context.getImageData(30, 30, 1, 1).data] })
  assert.deepEqual(capturedPixel, [217, 35, 77, 255], 'The overlay tint and border must not enter the native capture')
  await page.evaluate(() => document.getElementById('capture-pixel-marker').remove())
  await invoke('prototype_control_window', { label: 'main', options: { topmost: false } })
  await invoke('prototype_open_window', { kind: 'pin' })
  const pin = await findPage('pin')
  await pin.getByAltText('贴图验证原始像素').waitFor()
  await assert.rejects(invoke('prototype_read_capture', {}, widget), /无图片读取权限/)
  await assert.rejects(invoke('prototype_update_capture', { png: [1, 2, 3] }, widget), /无权/)
  await assert.rejects(invoke('prototype_update_capture', { png: [1, 2, 3] }))
  const beforeEditing = await page.evaluate(async () => Array.from(new Uint8Array(await window.__TAURI_INTERNALS__.invoke('prototype_read_capture'))))
  await page.getByRole('button', { name: '打开现有截图编辑器', exact: true }).click()
  const editor = page.getByTestId('shared-screenshot-editor')
  await editor.getByRole('button', { name: '矩形', exact: true }).waitFor()
  await waitFor(async () => !(await editor.getByRole('button', { name: '矩形', exact: true }).isDisabled()))
  await editor.getByRole('button', { name: '矩形', exact: true }).click()
  const canvas = editor.locator('.screenshot-image')
  await canvas.scrollIntoViewIfNeeded()
  const box = await canvas.boundingBox()
  assert.ok(box, 'The screenshot canvas must be laid out before drawing')
  for (const fraction of [.2, .8]) {
    assert.equal(await page.evaluate(({ x, y }) => Boolean(document.elementFromPoint(x, y)?.closest('.screenshot-viewport')), { x: box.x + box.width * fraction, y: box.y + box.height * fraction }), true, 'Drawing coordinates must hit the visible editor viewport')
  }
  await page.mouse.move(box.x + box.width * .2, box.y + box.height * .2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * .8, box.y + box.height * .8, { steps: 8 })
  await page.mouse.up()
  await editor.getByRole('button', { name: '撤销', exact: true }).click()
  await editor.getByRole('button', { name: '重做', exact: true }).click()
  await editor.getByRole('button', { name: '贴图', exact: true }).click()
  await waitFor(async () => (await invoke('prototype_diagnostics')).windows.some(window => window.label === 'probe-pin'))
  await waitFor(async () => {
    const errors = await editor.getByRole('alert').allTextContents()
    if (errors.some(Boolean)) throw Error('Shared editor export failed: ' + errors.join('; '))
    return editor.getByText('操作完成', { exact: true }).isVisible()
  })
  const flattened = await page.evaluate(async () => Array.from(new Uint8Array(await window.__TAURI_INTERNALS__.invoke('prototype_read_capture'))))
  assert.notDeepEqual(flattened, beforeEditing, 'Real WebView2 Worker flattening changes the captured image after drawing a rectangle')
  const annotatedPixels = await page.evaluate(async png => { const bitmap = await createImageBitmap(new Blob([new Uint8Array(png)], { type: 'image/png' })); const canvas = document.createElement('canvas'); canvas.width = bitmap.width; canvas.height = bitmap.height; const context = canvas.getContext('2d'); context.drawImage(bitmap, 0, 0); bitmap.close(); const pixels = context.getImageData(0, 0, canvas.width, canvas.height).data; let count = 0; for (let offset = 0; offset < pixels.length; offset += 4) { if (pixels[offset] === 255 && pixels[offset + 1] === 77 && pixels[offset + 2] === 87 && pixels[offset + 3] === 255) count++ } return count }, flattened)
  assert.ok(annotatedPixels > 20, 'The flattened PNG must contain the actual rectangle color, not merely different PNG encoding')
  await invoke('prototype_control_window', { label: 'main', options: { visible: false } })
  assert.equal((await invoke('prototype_diagnostics')).windows.find(window => window.label === 'main').visible, false)
  await invoke('prototype_restore_windows')
  assert.equal((await invoke('prototype_diagnostics')).windows.find(window => window.label === 'main').visible, true)
  await invoke('prototype_control_window', { label: 'probe-pin', options: { close: true } })
  await waitFor(async () => !(await invoke('prototype_diagnostics')).windows.some(window => window.label === 'probe-pin'))
  await assert.rejects(access(path.join(application.root, 'data', 'workspace.json')))
  assert.deepEqual(failures, [])
  const report = { ok: true, executable: application.executable, build: application.executable.includes(path.sep + 'release' + path.sep) ? 'release' : 'debug', version: initial.version, monitors: initial.monitors, checks: ['isolated-profile', 'real-webview2', 'transparent-window', 'native-position-size', 'native-topmost', 'native-alpha', 'native-mouse-through', 'recovery', 'caller-permissions', 'validation-before-mutation', 'overlay-physical-bounds', 'escape-cancel', 'png-region-capture', 'failed-capture-retry', 'pointer-selection-enter-preview', 'overlay-excluded-pixel-assertion', 'window-graphics-capture', 'shared-screenshot-editor-worker', 'annotation-undo-redo-pin', 'pin-preview', 'hide-restore', 'destroy-window', 'normal-quit'], pending: ['physical-mixed-dpi', 'actual-IME-composition', 'shell-file-drop', 'global-shortcut', 'sleep-display-hotplug', 'release-memory-gate'] }
  await mkdir('artifacts/tauri-migration', { recursive: true })
  await page.screenshot({ path: 'artifacts/tauri-migration/prototype-main.png', fullPage: true })
  void invoke('prototype_quit').catch(() => {})
  await waitFor(() => application.child.exitCode !== null)
  assert.equal(application.child.exitCode, 0)
  await writeFile('artifacts/tauri-migration/native-prototype.json', JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
} catch (error) {
  console.error('Native prototype UI:', await page.locator('body').innerText().catch(() => 'unavailable'))
  console.error('WebView errors:', failures, application.output())
  throw error
} finally { await application.close() }
